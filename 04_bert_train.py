# 🔧 Cell 3: Utility to load SST-2 style txt files into a DataFrame

def load_sst2_txt(path):
    """
    Reads a SST-2 style file: <label>\t<sentence>\n
    Returns a DataFrame with columns: ['label', 'text'].
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"File not found: {path}")

    labels = []
    texts  = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            parts = line.split("\t", 1)
            if len(parts) != 2:
                # Skip malformed lines but log them
                # (You can also assert here depending on your data quality)
                # print("Skipping malformed line:", line)
                continue
            label_str, text = parts
            try:
                label = int(label_str)
            except ValueError:
                # If label isn't an int for some reason, skip
                # print("Skipping line with non-int label:", line)
                continue
            labels.append(label)
            texts.append(text)

    df = pd.DataFrame({"label": labels, "text": texts})
    return df


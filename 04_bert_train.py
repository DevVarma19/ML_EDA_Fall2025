import json
from datetime import datetime

BERT_MODELS_DIR = os.path.join(PROJECT_ROOT, "bert_models")
os.makedirs(BERT_MODELS_DIR, exist_ok=True)

def now_str():
    return datetime.now().strftime("%Y-%m-%d_%H-%M-%S")

def train_bert_run(
    size: str,
    variant: str = "baseline",        # 'baseline' or 'eda'
    num_epochs: int = 3,
    batch_size: int = 16,
    learning_rate: float = 2e-5,
    weight_decay: float = 0.0,
):
    """
    Train BERT on a given size & variant ('baseline' / 'eda').

    Returns:
        meta_path (str), model_dir (str)
    """
    # Prepare data
    ds_train, ds_test, ds_meta = prepare_bert_datasets(size, variant)

    train_loader = DataLoader(ds_train, batch_size=batch_size, shuffle=True)
    test_loader  = DataLoader(ds_test,  batch_size=batch_size, shuffle=False)

    # Model
    model = AutoModelForSequenceClassification.from_pretrained(
        BERT_CHECKPOINT,
        num_labels=2,
    )
    model.to(device)

    # Optimizer
    optimizer = torch.optim.AdamW(model.parameters(), lr=learning_rate, weight_decay=weight_decay)

    total_steps = num_epochs * len(train_loader)
    print(f"[train_bert_run] size={size}, variant={variant}, epochs={num_epochs}, steps={total_steps}")

    # Training loop (simple)
    model.train()
    for epoch in range(num_epochs):
        epoch_loss = 0.0
        for batch in train_loader:
            optimizer.zero_grad()

            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels = batch["label"].to(device)

            outputs = model(
                input_ids=input_ids,
                attention_mask=attention_mask,
                labels=labels,
            )
            loss = outputs.loss
            loss.backward()
            optimizer.step()

            epoch_loss += loss.item()

        avg_loss = epoch_loss / max(1, len(train_loader))
        print(f"  Epoch {epoch+1}/{num_epochs} - train loss: {avg_loss:.4f}")

    # ---- Evaluation on train and test ----
    train_metrics, train_cm, train_curves = evaluate_bert_model(model, train_loader, device)
    test_metrics, test_cm, test_curves = evaluate_bert_model(model, test_loader, device)

    print("[train_bert_run] Test metrics:", test_metrics)

    # ---- Save model ----
    timestamp = now_str()
    stub = f"{DATASET_NAME}__size-{size}__bert__{variant}__{timestamp}"
    model_dir = os.path.join(BERT_MODELS_DIR, stub)
    os.makedirs(model_dir, exist_ok=True)
    model.save_pretrained(model_dir)
    tokenizer.save_pretrained(model_dir)

    # ---- Save metadata JSON ----
    meta = {
        "dataset": DATASET_NAME,
        "size": size,
        "variant": variant,         # 'baseline' / 'eda'
        "method": ds_meta["method"],
        "alpha": ds_meta["alpha"],
        "model_family": "bert",
        "model_type": "bert",
        "checkpoint": BERT_CHECKPOINT,
        "max_seq_len": MAX_SEQ_LEN,
        "epochs": num_epochs,
        "batch_size": batch_size,
        "learning_rate": learning_rate,
        "weight_decay": weight_decay,
        "train_path": ds_meta["train_path"],
        "test_path": ds_meta["test_path"],
        "timestamp": timestamp,
        "paths": {
            "model": model_dir,
        },
        "train_metrics": train_metrics,
        "test_metrics": test_metrics,
        "train_confusion_matrix": train_cm.tolist(),
        "test_confusion_matrix": test_cm.tolist(),
        "train_curves": train_curves,
        "test_curves": test_curves,
    }

    meta_path = os.path.join(BERT_MODELS_DIR, stub + ".json")
    with open(meta_path, "w") as f:
        json.dump(meta, f, indent=2)

    print("✅ Saved model to:", model_dir)
    print("✅ Saved metadata to:", meta_path)

    return meta_path, model_dir


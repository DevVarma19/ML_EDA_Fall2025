from datasets import Dataset
from torch.utils.data import DataLoader

def df_to_hf_dataset(df: pd.DataFrame):
    """
    Convert a DataFrame with columns ['text', 'label'] into a HF Dataset.
    """
    return Dataset.from_pandas(df, preserve_index=False)

def tokenize_function(batch):
    return tokenizer(
        batch["text"],
        truncation=True,
        padding="max_length",
        max_length=MAX_SEQ_LEN,
    )

def prepare_bert_datasets(size: str, variant: str):
    """
    size: one of SIZE_SPLITS (e.g., '1_tiny')
    variant: 'baseline' or 'eda'

    Returns:
        train_dataset, test_dataset  (HF Datasets with torch format)
        meta_info (dict with paths + method/alpha if EDA)
    """
    assert size in SIZE_SPLITS, f"Unknown size: {size}"
    assert variant in ("baseline", "eda"), f"Unknown variant: {variant}"

    if variant == "baseline":
        train_path = get_baseline_train_path(size)
        method = None
        alpha  = None
    else:
        train_path = get_eda_train_path(size)
        cfg = BEST_EDA_PER_SIZE[size]
        method = cfg["method"]
        alpha  = cfg["alpha"]

    # load into DataFrames
    train_df = load_sst2_txt(train_path)
    test_df  = load_sst2_txt(TEST_PATH)

    print(f"[prepare_bert_datasets] size={size}, variant={variant}")
    print("  train_path:", train_path, " ->", train_df.shape)
    print("  test_path :", TEST_PATH,   " ->", test_df.shape)

    # HF Datasets
    ds_train = df_to_hf_dataset(train_df)
    ds_test  = df_to_hf_dataset(test_df)

    # tokenize
    ds_train = ds_train.map(tokenize_function, batched=True)
    ds_test  = ds_test.map(tokenize_function, batched=True)

    # keep only needed columns
    ds_train.set_format(
        type="torch",
        columns=["input_ids", "attention_mask", "label"],
    )
    ds_test.set_format(
        type="torch",
        columns=["input_ids", "attention_mask", "label"],
    )

    meta_info = {
        "size": size,
        "variant": variant,
        "train_path": train_path,
        "test_path": TEST_PATH,
        "method": method,
        "alpha": alpha,
    }

    return ds_train, ds_test, meta_info

# 🔹 Cell 6: Metric helpers for binary classification

def compute_metrics_full(y_true, y_prob_pos):
    """
    y_true: 1D array of ints (0/1)
    y_prob_pos: 1D array of probabilities for the positive class
    """
    y_true = np.asarray(y_true)
    y_prob_pos = np.asarray(y_prob_pos)
    y_pred = (y_prob_pos >= 0.5).astype(int)

    acc = accuracy_score(y_true, y_pred)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="binary", zero_division=0
    )

    # AUROC / PR-AUC (handle edge cases)
    try:
        auroc = roc_auc_score(y_true, y_prob_pos)
    except Exception:
        auroc = float("nan")

    try:
        pr_auc = average_precision_score(y_true, y_prob_pos)
    except Exception:
        pr_auc = float("nan")

    cm = confusion_matrix(y_true, y_pred)

    # curves
    try:
        fpr, tpr, _ = roc_curve(y_true, y_prob_pos)
    except Exception:
        fpr, tpr = np.array([]), np.array([])

    try:
        prec_curve, rec_curve, _ = precision_recall_curve(y_true, y_prob_pos)
    except Exception:
        prec_curve, rec_curve = np.array([]), np.array([])

    metrics = {
        "acc": float(acc),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "auroc": None if np.isnan(auroc) else float(auroc),
        "pr_auc": None if np.isnan(pr_auc) else float(pr_auc),
    }

    curves = {
        "roc_fpr": fpr.tolist(),
        "roc_tpr": tpr.tolist(),
        "pr_precision": prec_curve.tolist(),
        "pr_recall": rec_curve.tolist(),
    }

    return metrics, cm, curves

# 🔹 Cell 7: Evaluate a BERT model on a PyTorch DataLoader

def evaluate_bert_model(model, dataloader, device):
    model.eval()
    all_probs = []
    all_labels = []

    with torch.no_grad():
        for batch in dataloader:
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels = batch["label"].cpu().numpy()

            outputs = model(input_ids=input_ids, attention_mask=attention_mask)
            logits = outputs.logits.detach().cpu().numpy()
            probs = torch.softmax(torch.tensor(logits), dim=1).numpy()

            all_probs.append(probs)
            all_labels.append(labels)

    all_probs = np.concatenate(all_probs, axis=0)      # (N, 2)
    all_labels = np.concatenate(all_labels, axis=0)    # (N,)

    # probability of positive class = column 1
    y_prob_pos = all_probs[:, 1]
    metrics, cm, curves = compute_metrics_full(all_labels, y_prob_pos)
    return metrics, cm, curves

